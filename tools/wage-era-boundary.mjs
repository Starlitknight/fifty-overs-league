// wage-era-boundary.mjs — THE STOP GATE FOR A GLOBAL WAGE-LAW CHANGE.
//
// Phase 5 asks whether the absolute wage anchor is stale. Before any constant
// moves, one question has to be answered honestly, and the brief is explicit
// that it may not be assumed: DOES THE ERA-2 ECONOMY GATE PROTECT A GLOBAL
// PLAYER-PRICE FUNCTION?
//
// It does not, and the reason is not in economy.mjs at all. The chain is:
//
//   living.mjs evolveCountry()      every club, EVERY settle
//     -> host.derive(squad)         enginehost.mjs, into the shipped page
//        -> jsDerive(p)             00-core.js
//           -> p.wage = foWageOf(p.rating, talents, 1)
//     -> the fold copies `wage` straight back onto the player row
//
// The fold derives a man's card from his skills on every settle - deliberately,
// because a stored card that drifts from the cricketer beneath it broke the
// spectator contract once already. Wage rides along in that same list of
// derived fields. So foWageOf is not an era-2 law being read behind an era
// gate; it is a global player-price function evaluated for every cricketer in
// the world, three times an hour, era-1 clubs included.
//
// This proves it by EXPERIMENT rather than by reading the call chain, because
// reading a call chain is how the last two of these were got wrong. It patches
// the shipped asset's FO_WAGE_MID, loads a second engine host from it, and
// derives the SAME squad through both.
//
//   node tools/wage-era-boundary.mjs
//
// Touches assets/ only in memory of a backup it restores and verifies before
// it exits.
import { readFileSync, writeFileSync, copyFileSync, unlinkSync } from 'node:fs';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { makeHost } from '../server/enginehost.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const $ = n => '$' + Math.round(n).toLocaleString();
const L = s => console.log(s);
let fails = 0;
const ok = (c, w) => { if (!c) { fails++; L('   FAIL  ' + w); } else L('   ok    ' + w); };

// the one asset index.html names - the asset ritual means there is exactly one
const idx = readFileSync(path.join(root, 'index.html'), 'utf8');
const assetName = (/src\s*=\s*["']([^"']*fo-[^"']+\.js)["']/.exec(idx) || [])[1];
if (!assetName) { console.error('no fingerprinted asset in index.html - run ./build.sh'); process.exit(2); }
const assetPath = path.join(root, assetName);
const backup = assetPath + '.era-probe-backup';
const sha = f => createHash('sha256').update(readFileSync(f)).digest('hex');
const before = sha(assetPath);

L('');
L('THE ERA-1 BOUNDARY FOR A GLOBAL WAGE CHANGE');
L('='.repeat(78));
L('');
L('   asset under test   ' + assetName);
L('   sha256            ' + before.slice(0, 16) + '...');
L('');

// a squad to price. Generated by the shipped generator so these are real
// cricketers with real skills, not hand-built rows.
const host = makeHost();
const squad = host.genSquad(4242, 'eng', 'balanced', null, 1.0, null).slice(0, 15);
const rate = p => p.rating;
const shipped = host.derive(squad.map(p => ({ ...p })));

L('1. THE SHIPPED LAW, ON A REAL DEALT SQUAD');
L('');
L('     rating   card    wage');
for (const p of shipped.slice(0, 6)) {
  L('   ' + String(rate(p)).padStart(8) + String(Math.round(rate(p) / 1000)).padStart(7)
    + $(p.wage).padStart(9));
}
const shippedBill = shipped.reduce((a, p) => a + (p.wage || 0), 0);
L('   ...');
L('   fifteen-man bill   ' + $(shippedBill) + ' a round');
L('');

// ---------------------------------------------------------------------------
// THE EXPERIMENT. Move the midpoint by a factor the eye cannot miss, reload a
// host from the patched asset, and derive the identical squad again. Nothing
// about era is touched: no season is dated, no era gate is crossed. If wages
// move, they move for every club in the world regardless of era.
// ---------------------------------------------------------------------------
copyFileSync(assetPath, backup);
let patched = null, patchedBill = 0;
try {
  const src = readFileSync(assetPath, 'utf8');
  const m = /const FO_WAGE_MID=(\d+)/.exec(src);
  if (!m) throw new Error('FO_WAGE_MID not found in the built asset');
  const oldMid = +m[1], newMid = Math.round(oldMid / 2);
  writeFileSync(assetPath, src.replace(m[0], 'const FO_WAGE_MID=' + newMid));
  L('2. THE SAME SQUAD, WITH FO_WAGE_MID HALVED (' + oldMid + ' -> ' + newMid + ')');
  L('');
  const host2 = makeHost();
  patched = host2.derive(squad.map(p => ({ ...p })));
  patchedBill = patched.reduce((a, p) => a + (p.wage || 0), 0);
  L('     rating   card    wage    was');
  for (let i = 0; i < 6; i++) {
    L('   ' + String(rate(patched[i])).padStart(8)
      + String(Math.round(rate(patched[i]) / 1000)).padStart(7)
      + $(patched[i].wage).padStart(9) + $(shipped[i].wage).padStart(9));
  }
  L('   ...');
  L('   fifteen-man bill   ' + $(patchedBill) + ' a round   (was ' + $(shippedBill) + ')');
} finally {
  copyFileSync(backup, assetPath);
  unlinkSync(backup);
}
const after = sha(assetPath);

L('');
L('3. WHAT THAT MEANS');
L('');
const moved = patched.filter((p, i) => p.wage !== shipped[i].wage).length;
const ratingsHeld = patched.every((p, i) => p.rating === shipped[i].rating);
ok(moved === patched.length,
  'every one of the ' + patched.length + ' men was repriced by the constant alone ('
  + moved + ' of ' + patched.length + ')');
ok(ratingsHeld,
  'and not one rating moved - this is the WAGE law, not the player');
ok(Math.abs(patchedBill / shippedBill - 0.5) < 0.01,
  'the bill scaled with the midpoint (' + (patchedBill / shippedBill).toFixed(3)
  + 'x for a 0.5x constant)');
L('');
L('   NO ERA WAS INVOLVED. No season was dated, no era gate was crossed, and');
L('   economy.mjs was never called. The repricing happened inside host.derive,');
L('   which server/living.mjs runs for EVERY club on EVERY settle and whose');
L('   result it copies onto the player row - `wage` is in that list beside');
L('   `rating` and `bat`. An era-1 club in production is folded by exactly');
L('   this path three times an hour.');
L('');
ok(before === after, 'the asset was restored byte-identical (sha ' + after.slice(0, 16) + '...)');

L('');
L('='.repeat(78));
L(fails === 0
  ? 'RESULT: a global foWageOf change REPRICES ERA-1 PLAYERS. The era-2 economy\n'
    + '        gate does not protect it. Phase 5 section 4 STOP condition is met:\n'
    + '        any wage change needs a versioning mechanism before it can ship.'
  : 'PROBE INCONCLUSIVE - ' + fails + ' check(s) failed');
process.exit(fails === 0 ? 0 : 1);
